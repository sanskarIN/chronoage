import { readFile } from 'node:fs/promises';

const root = new URL('../', import.meta.url);
const packageJson = JSON.parse(await readFile(new URL('package.json', root), 'utf8'));

function selectedTargets(args) {
  const explicit = new Set(args.filter((arg) => arg.startsWith('--')));
  if (explicit.size === 0 || explicit.has('--all')) return new Set(['npm', 'cargo']);

  const allowed = new Set(['--npm', '--cargo']);
  for (const arg of explicit) {
    if (!allowed.has(arg)) {
      throw new Error(`Unknown lockfile target ${arg}. Use --npm, --cargo, or --all.`);
    }
  }

  return new Set([...explicit].map((arg) => arg.slice(2)));
}

function sameRecord(actual = {}, expected = {}) {
  const actualEntries = Object.entries(actual).sort(([left], [right]) => left.localeCompare(right));
  const expectedEntries = Object.entries(expected).sort(([left], [right]) => left.localeCompare(right));
  return JSON.stringify(actualEntries) === JSON.stringify(expectedEntries);
}

async function checkNpmLockfile(failures) {
  let lockfile;
  try {
    lockfile = JSON.parse(await readFile(new URL('package-lock.json', root), 'utf8'));
  } catch (error) {
    failures.push(
      error instanceof SyntaxError
        ? 'npm lockfile: package-lock.json is not valid JSON'
        : 'npm lockfile: package-lock.json is missing; generate it with the pinned Node/npm toolchain',
    );
    return;
  }

  if (lockfile.lockfileVersion !== 3) {
    failures.push(
      `npm lockfile: lockfileVersion=${JSON.stringify(lockfile.lockfileVersion)} expected=3 for the current npm toolchain`,
    );
  }

  if (lockfile.name !== packageJson.name || lockfile.version !== packageJson.version) {
    failures.push(
      `npm lockfile: root identity ${JSON.stringify(`${lockfile.name}@${lockfile.version}`)} does not match package.json ${JSON.stringify(`${packageJson.name}@${packageJson.version}`)}`,
    );
  }

  const rootPackage = lockfile.packages?.[''];
  if (!rootPackage) {
    failures.push('npm lockfile: missing packages[""] root package metadata');
    return;
  }

  if (rootPackage.name !== packageJson.name || rootPackage.version !== packageJson.version) {
    failures.push('npm lockfile: packages[""] name/version do not match package.json');
  }

  if (!sameRecord(rootPackage.dependencies, packageJson.dependencies)) {
    failures.push('npm lockfile: packages[""] dependencies do not exactly match package.json');
  }

  if (!sameRecord(rootPackage.devDependencies, packageJson.devDependencies)) {
    failures.push('npm lockfile: packages[""] devDependencies do not exactly match package.json');
  }
}

function cargoPackageValue(source, key) {
  const packageSection = source.match(/\[package\]([\s\S]*?)(?:\n\[|$)/)?.[1] ?? '';
  return packageSection.match(new RegExp(`^${key}\\s*=\\s*["']([^"']+)["']`, 'm'))?.[1];
}

async function checkCargoLockfile(failures) {
  const cargoToml = await readFile(new URL('src-tauri/Cargo.toml', root), 'utf8');
  const cargoName = cargoPackageValue(cargoToml, 'name');
  const cargoVersion = cargoPackageValue(cargoToml, 'version');

  let lockfile;
  try {
    lockfile = await readFile(new URL('src-tauri/Cargo.lock', root), 'utf8');
  } catch {
    failures.push(
      'Cargo lockfile: src-tauri/Cargo.lock is missing; generate it with the pinned Rust/Cargo toolchain',
    );
    return;
  }

  if (!lockfile.startsWith('# This file is automatically @generated by Cargo.')) {
    failures.push('Cargo lockfile: missing Cargo generated-file header');
  }

  const lockVersion = Number(lockfile.match(/^version\s*=\s*(\d+)\s*$/m)?.[1]);
  if (!Number.isInteger(lockVersion) || lockVersion < 3 || lockVersion > 4) {
    failures.push(`Cargo lockfile: unsupported lockfile format version ${JSON.stringify(lockVersion)}`);
  }

  if (!cargoName || !cargoVersion) {
    failures.push('Cargo manifest: unable to read package name/version for lockfile verification');
    return;
  }

  const packageBlocks = [...lockfile.matchAll(/\[\[package\]\]([\s\S]*?)(?=\n\[\[package\]\]|$)/g)].map(
    (match) => match[1],
  );
  const rootPackage = packageBlocks.find(
    (block) =>
      new RegExp(`^name\\s*=\\s*"${cargoName.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')}"\\s*$`, 'm').test(
        block,
      ) &&
      new RegExp(
        `^version\\s*=\\s*"${cargoVersion.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')}"\\s*$`,
        'm',
      ).test(block),
  );

  if (!rootPackage) {
    failures.push(`Cargo lockfile: missing root package ${cargoName}@${cargoVersion}`);
  }
}

let targets;
try {
  targets = selectedTargets(process.argv.slice(2));
} catch (error) {
  console.error(error instanceof Error ? error.message : String(error));
  process.exit(2);
}

const failures = [];
if (targets.has('npm')) await checkNpmLockfile(failures);
if (targets.has('cargo')) await checkCargoLockfile(failures);

if (failures.length > 0) {
  console.error('Release lockfile preflight failed:');
  failures.forEach((failure) => console.error(`- ${failure}`));
  process.exitCode = 1;
} else {
  console.log(`Release lockfile preflight passed for: ${[...targets].join(', ')}.`);
}
